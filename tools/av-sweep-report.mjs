#!/usr/bin/env node
// Merges test-results/av-sweep/<core|full>-*.json (written by the av-evasion-sweep shards) and prints pass-rate matrices.
// usage: node tools/av-sweep-report.mjs [core|full]   (default full if present)
import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = join(process.cwd(), 'test-results', 'av-sweep')
const kind = process.argv[2] ?? (readdirSync(dir).some((f) => f.startsWith('full-')) ? 'full' : 'core')
const all = readdirSync(dir).filter((f) => f.startsWith(`${kind}-`)).flatMap((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
const win = all.filter((r) => !r.unwinnable)
const cell = (rs) => (rs.length ? `${rs.filter((r) => r.pass).length}/${rs.length}` : '-')
console.log(`AV sweep (${kind}): ${all.length} cases, ${all.length - win.length} classified unwinnable (excluded), winnable pass ${cell(win)}; unwinnable that passed anyway ${cell(all.filter((r) => r.unwinnable)).replace(/\/.*/, '')}/${all.length - win.length}`)
const keys = [...new Set(all.flatMap((r) => Object.keys(r.params)))]
for (const fam of [...new Set(all.map((r) => r.family))]) {
  const rs = win.filter((r) => r.family === fam)
  console.log(`\n${fam}: ${cell(rs)}`)
  for (const k of keys) {
    const vals = [...new Set(rs.map((r) => r.params[k]).filter((v) => v != null))]
    if (vals.length < 2) continue
    console.log(`  by ${k.padEnd(8)} ${vals.map((v) => `${v}: ${cell(rs.filter((r) => r.params[k] === v))}`).join('  ')}`)
  }
}
const tier = (lo, hi) => win.filter((r) => r.margin >= lo && r.margin < hi)
console.log(`\nby oracle margin (best achievable min gap): robust >= 2 m: ${cell(tier(2, 99))}   marginal 0.3-2 m: ${cell(tier(0.3, 2))}`)
console.log('\nFAIL (winnable):')
for (const r of win.filter((r) => !r.pass)) console.log(`  ${r.id.padEnd(34)} margin ${r.margin.toFixed(1).padStart(3)} ${r.failed.join('; ')} ${r.firstContact}`)

if (process.argv.includes('--write-baseline')) {
  const { writeFileSync } = await import('node:fs')
  const ids = win.filter((r) => r.pass).map((r) => r.id).sort()
  const src = `// Generated by \`node tools/av-sweep-report.mjs full --write-baseline\` after an AV_SWEEP=full run: winnable sweep cases the AV passes today.\n// The sweep asserts these keep passing (regression guard); other winnable cases are reported only. Add ids as the AV improves.\nexport const SWEEP_BASELINE_PASS = new Set<string>([\n${ids.map((i) => `  '${i}',`).join('\n')}\n])\n`
  writeFileSync(join(process.cwd(), 'src/test/fixtures/avEvasionSweepBaseline.ts'), src)
  console.log(`\nbaseline written: ${ids.length} ids`)
}
